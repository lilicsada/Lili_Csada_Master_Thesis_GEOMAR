function ...
    y_smooth = ...
    gaussian_smooth_matrix( ...
    y, ...
    dt, ...
    window_kyr)


    y = ...
        ensure_column_matrix( ...
        y);


    window_points = ...
        round( ...
        window_kyr ...
        / dt);


    if ...
            mod( ...
            window_points, ...
            2) ...
            == 0

        window_points = ...
            window_points ...
            + 1;

    end


    half_window = ...
        floor( ...
        window_points ...
        / 2);


    x = ...
        ( ...
        -half_window : ...
        half_window ...
        )';


    sigma_points = ...
        window_points ...
        / 6;


    kernel = ...
        exp( ...
        -0.5 ...
        .* ...
        ( ...
        x ...
        ./ sigma_points ...
        ).^2);


    kernel = ...
        kernel ...
        ./ sum(kernel);


    valid = ...
        isfinite(y);


    y0 = ...
        y;


    y0(~valid) = ...
        0;


    numerator = ...
        conv2( ...
        y0, ...
        kernel, ...
        "same");


    denominator = ...
        conv2( ...
        double(valid), ...
        kernel, ...
        "same");


    y_smooth = ...
        numerator ...
        ./ denominator;


    y_smooth( ...
        denominator ...
        == 0) = ...
        NaN;


end



