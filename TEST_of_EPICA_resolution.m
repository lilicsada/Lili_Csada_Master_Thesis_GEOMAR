function ...
    [age, proxy] = ...
    read_epica_record( ...
    filename, ...
    age_min, ...
    age_max)


    if ...
            ~isfile(filename)

        error( ...
            "EPICA file not found: %s", ...
            filename);

    end


    M = ...
        readmatrix( ...
        filename);


    if ...
            size(M, 2) ...
            < 2

        error( ...
            [ ...
            "%s must contain age and proxy values " ...
            "in its first two columns." ...
            ], ...
            filename);

    end


    age = ...
        M(:, 1);


    proxy = ...
        M(:, 2);


    valid = ...
        isfinite(age) & ...
        isfinite(proxy);


    age = ...
        age(valid);


    proxy = ...
        proxy(valid);


    % Convert years to kyr if necessary

    if ...
            max(age) ...
            > 5000

        age = ...
            age ...
            / 1000;

    end


    [age, order] = ...
        sort( ...
        age, ...
        "ascend");


    proxy = ...
        proxy(order);


    [age, unique_index] = ...
        unique( ...
        age, ...
        "stable");


    proxy = ...
        proxy(unique_index);


    keep = ...
        age >= age_min & ...
        age <= age_max;


    age = ...
        age(keep);


    proxy = ...
        proxy(keep);


    if ...
            numel(age) ...
            < 100

        error( ...
            "Too few EPICA observations remain.");

    end


end



