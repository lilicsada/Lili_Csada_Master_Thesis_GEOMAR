%% ============================================================
% EPICA TEMPORAL-RESOLUTION EFFECT TEST
%
% Real EPICA:
%   (a) Original temporal resolution
%   (b) Thirumalai-style mMCV
%   (c) <2 kyr and 2--10 kyr frequency decomposition
%   (d) Thesis Hilbert-amplitude mMCV
%
% Synthetic experiment:
%   (e) Thirumalai-style resolution test
%   (f) Hilbert-amplitude resolution test
%



% 1. SETTINGS
opts.epica_file = "Epica_deuterium.txt";


% Time axis
opts.age_min_kyr = 0;
opts.age_max_kyr = 801;
opts.dt_kyr = 0.1;                  % 100 years
opts.interp_method = "pchip";


% Filtering
opts.filter_order = 4;
opts.thirumalai_cutoff_kyr = 10;    % retain periods <10 kyr
opts.split_period_kyr = 2;          % separate <2 and 2--10 kyr
opts.pad_kyr = 10;


% mMCV and smoothing
opts.rolling_window_kyr = 2;
opts.gaussian_window_kyr = 100;
opts.resolution_smooth_kyr = 20;    % visualisation only


% Monte Carlo
opts.n_realizations = 10000;
opts.chunk_size = 50;
opts.random_seed = 20260713;
opts.burn_in_steps = 2000;
opts.output_dt_kyr = 1.0;
opts.percentiles = [5 95];


% Plot appearance
opts.font_name = "Cambria Math";
opts.axis_font_size = 8.5;
opts.ylabel_font_size = 8.5;
opts.xlabel_font_size = 9;
opts.panel_heading_font_size = 9;
opts.legend_font_size = 7.5;

opts.figure_position = [2 2 18.2 18.5];
% Export
opts.export_figure = true;
opts.output_name = ...
    "EPICA_temporal_resolution_test_6panel";




% 2. READ AND INTERPOLATE THE FULL EPICA RECORD


[age_obs, deltaD_obs] = ...
    read_epica_record( ...
    opts.epica_file, ...
    opts.age_min_kyr, ...
    opts.age_max_kyr);


age_start = ...
    ceil( ...
    max( ...
    opts.age_min_kyr, ...
    min(age_obs)) ...
    / opts.dt_kyr) ...
    * opts.dt_kyr;


age_end = ...
    floor( ...
    min( ...
    opts.age_max_kyr, ...
    max(age_obs)) ...
    / opts.dt_kyr) ...
    * opts.dt_kyr;


age = ...
    ( ...
    age_start : ...
    opts.dt_kyr : ...
    age_end ...
    )';


keep_obs = ...
    age_obs >= age(1) & ...
    age_obs <= age(end);


age_obs = ...
    age_obs(keep_obs);


deltaD_obs = ...
    deltaD_obs(keep_obs);


deltaD_interp = ...
    interp1( ...
    age_obs, ...
    deltaD_obs, ...
    age, ...
    opts.interp_method);


fprintf( ...
    "\nEPICA loaded: %d observations, %.1f--%.1f kyr BP.\n", ...
    numel(age_obs), ...
    age(1), ...
    age(end));




% 3. DESIGN FILTERS


fs = ...
    1 / opts.dt_kyr;


nyquist = ...
    fs / 2;


% High-pass filter retaining periods shorter than 10 kyr

[b_hp10, a_hp10] = ...
    butter( ...
    opts.filter_order, ...
    (1 / opts.thirumalai_cutoff_kyr) ...
    / nyquist, ...
    "high");


% High-pass filter retaining periods shorter than 2 kyr

[b_hp2, a_hp2] = ...
    butter( ...
    opts.filter_order, ...
    (1 / opts.split_period_kyr) ...
    / nyquist, ...
    "high");


% Band-pass filter retaining periods between 2 and 10 kyr

[b_bp2_10, a_bp2_10] = ...
    butter( ...
    opts.filter_order, ...
    [ ...
    1 / opts.thirumalai_cutoff_kyr ...
    1 / opts.split_period_kyr ...
    ] ...
    / nyquist, ...
    "bandpass");


% Mirror-padding length

npad = ...
    round( ...
    opts.pad_kyr ...
    / opts.dt_kyr);


npad = ...
    max( ...
    npad, ...
    3 * max( ...
    [ ...
    length(a_hp10) ...
    length(b_hp10) ...
    length(a_hp2) ...
    length(b_hp2) ...
    length(a_bp2_10) ...
    length(b_bp2_10) ...
    ]));


% Half-width of the centred 2-kyr moving window

half_window_points = ...
    round( ...
    opts.rolling_window_kyr ...
    / ...
    (2 * opts.dt_kyr));




% 4. ESTIMATE EPICA-DERIVED AR(1) PARAMETERS

EPICA = ...
    struct();


% Remove the 100-kyr Gaussian-smoothed long-term component

EPICA.deltaD_long_term = ...
    gaussian_smooth_matrix( ...
    deltaD_interp, ...
    opts.dt_kyr, ...
    opts.gaussian_window_kyr);


EPICA.deltaD_residual = ...
    deltaD_interp ...
    - EPICA.deltaD_long_term;


% Lag-1 autocorrelation

x_previous = ...
    EPICA.deltaD_residual(1:end-1);


x_next = ...
    EPICA.deltaD_residual(2:end);


valid_pair = ...
    isfinite(x_previous) & ...
    isfinite(x_next);


EPICA.phi = ...
    corr( ...
    x_previous(valid_pair), ...
    x_next(valid_pair));


EPICA.phi = ...
    max( ...
    min( ...
    EPICA.phi, ...
    0.999), ...
    -0.999);


% Standard deviation of the detrended EPICA record

EPICA.sigma_residual = ...
    std( ...
    EPICA.deltaD_residual, ...
    0, ...
    "omitnan");


fprintf( ...
    "EPICA AR(1): phi = %.6f, residual SD = %.6f.\n", ...
    EPICA.phi, ...
    EPICA.sigma_residual);




% 5. CALCULATE REAL EPICA mMCV METRICS



% ------------------------------------------------------------
% Thirumalai-style metric:
% <10 kyr high-pass-filtered signal
% + centred 2-kyr rolling standard deviation
% ------------------------------------------------------------

[~, EPICA.mmcv_thirumalai] = ...
    filtered_moving_std_with_padding( ...
    deltaD_interp, ...
    b_hp10, ...
    a_hp10, ...
    npad, ...
    half_window_points);


% ------------------------------------------------------------
% Frequency decomposition of the rolling-SD metric
% ------------------------------------------------------------

[~, EPICA.mmcv_lt2] = ...
    filtered_moving_std_with_padding( ...
    deltaD_interp, ...
    b_hp2, ...
    a_hp2, ...
    npad, ...
    half_window_points);


[~, EPICA.mmcv_2_10_movstd] = ...
    filtered_moving_std_with_padding( ...
    deltaD_interp, ...
    b_bp2_10, ...
    a_bp2_10, ...
    npad, ...
    half_window_points);



% Thesis metric:
% 2--10 kyr Hilbert amplitude


[~, hilbert_amplitude] = ...
    filtered_hilbert_with_padding( ...
    deltaD_interp, ...
    b_bp2_10, ...
    a_bp2_10, ...
    npad);


EPICA.mmcv_hilbert_z = ...
    zscore_columns( ...
    hilbert_amplitude);



% 100-kyr long-term components for visualisation


EPICA.mmcv_thirumalai_smooth = ...
    gaussian_smooth_matrix( ...
    EPICA.mmcv_thirumalai, ...
    opts.dt_kyr, ...
    opts.gaussian_window_kyr);


EPICA.mmcv_lt2_smooth = ...
    gaussian_smooth_matrix( ...
    EPICA.mmcv_lt2, ...
    opts.dt_kyr, ...
    opts.gaussian_window_kyr);


EPICA.mmcv_2_10_movstd_smooth = ...
    gaussian_smooth_matrix( ...
    EPICA.mmcv_2_10_movstd, ...
    opts.dt_kyr, ...
    opts.gaussian_window_kyr);


EPICA.mmcv_hilbert_z_smooth = ...
    gaussian_smooth_matrix( ...
    EPICA.mmcv_hilbert_z, ...
    opts.dt_kyr, ...
    opts.gaussian_window_kyr);




% 6. CALCULATE ORIGINAL EPICA TEMPORAL RESOLUTION


EPICA.sampling_interval_raw = ...
    diff(age_obs);


EPICA.sampling_interval_midpoint = ...
    ( ...
    age_obs(1:end-1) ...
    + age_obs(2:end) ...
    ) ...
    / 2;


% Place observation-spacing estimates on the regular time grid

EPICA.sampling_interval = ...
    interp1( ...
    EPICA.sampling_interval_midpoint, ...
    EPICA.sampling_interval_raw, ...
    age, ...
    "nearest", ...
    "extrap");


% Smooth only for visualisation

EPICA.sampling_interval_smooth = ...
    gaussian_smooth_matrix( ...
    EPICA.sampling_interval, ...
    opts.dt_kyr, ...
    opts.resolution_smooth_kyr);


fprintf( ...
    "Median EPICA spacing = %.0f yr; maximum = %.0f yr.\n", ...
    1000 ...
    * median( ...
    EPICA.sampling_interval_raw, ...
    "omitnan"), ...
    1000 ...
    * max( ...
    EPICA.sampling_interval_raw, ...
    [], ...
    "omitnan"));




% 7. SYNTHETIC RESOLUTION EXPERIMENT


rng( ...
    opts.random_seed, ...
    "twister");


output_stride = ...
    round( ...
    opts.output_dt_kyr ...
    / opts.dt_kyr);


if ...
        abs( ...
        output_stride ...
        * opts.dt_kyr ...
        - opts.output_dt_kyr) ...
        > 1e-10

    error( ...
        [ ...
        "opts.output_dt_kyr must be an integer " ...
        "multiple of opts.dt_kyr." ...
        ]);

end


output_index = ...
    ( ...
    1 : ...
    output_stride : ...
    numel(age) ...
    )';


age_output = ...
    age(output_index);


n_output = ...
    numel(age_output);


n_real = ...
    opts.n_realizations;


% Preallocate ensemble matrices

SYN = ...
    struct();


SYN.thir_uniform = ...
    nan( ...
    n_output, ...
    n_real, ...
    "single");


SYN.thir_epica_resolution = ...
    nan( ...
    n_output, ...
    n_real, ...
    "single");


SYN.hilbert_uniform = ...
    nan( ...
    n_output, ...
    n_real, ...
    "single");


SYN.hilbert_epica_resolution = ...
    nan( ...
    n_output, ...
    n_real, ...
    "single");


% Adaptive burn-in

adaptive_burn_in = ...
    ceil( ...
    20 ...
    / max( ...
    1 - abs(EPICA.phi), ...
    1e-4));


burn_in = ...
    max( ...
    opts.burn_in_steps, ...
    adaptive_burn_in);


fprintf( ...
    "\nRunning %d stationary AR(1) realisations...\n", ...
    n_real);




% 8. MONTE CARLO LOOP


for first_realisation = ...
        1 : ...
        opts.chunk_size : ...
        n_real


    last_realisation = ...
        min( ...
        first_realisation ...
        + opts.chunk_size ...
        - 1, ...
        n_real);


    column_index = ...
        first_realisation : ...
        last_realisation;


    n_chunk = ...
        numel( ...
        column_index);


    fprintf( ...
        "  %d--%d of %d\n", ...
        first_realisation, ...
        last_realisation, ...
        n_real);


    
    % Generate Gaussian innovations for an approximately
    % unit-variance stationary AR(1) process
    
    innovations = ...
        sqrt( ...
        1 - EPICA.phi^2) ...
        .* randn( ...
        numel(age) ...
        + burn_in, ...
        n_chunk);


   
    % Generate raw AR(1) realisations
  

    synthetic_raw = ...
        filter( ...
        1, ...
        [1 -EPICA.phi], ...
        innovations, ...
        [], ...
        1);


    % Remove burn-in

    synthetic_raw = ...
        synthetic_raw( ...
        burn_in + 1 : end, ...
        :);


    
    % Standardise each realisation and scale it to the
    % standard deviation of the detrended EPICA record
  

    synthetic_standardised = ...
        zscore_columns( ...
        synthetic_raw);


    synthetic_uniform = ...
        EPICA.sigma_residual ...
        .* synthetic_standardised;


    
    % Apply the original EPICA sampling structure
   

    synthetic_at_observations = ...
        interp1( ...
        age, ...
        synthetic_uniform, ...
        age_obs, ...
        opts.interp_method);


    synthetic_epica_resolution = ...
        interp1( ...
        age_obs, ...
        synthetic_at_observations, ...
        age, ...
        opts.interp_method);


   
    % Thirumalai-style mMCV
    

    [~, thir_uniform] = ...
        filtered_moving_std_with_padding( ...
        synthetic_uniform, ...
        b_hp10, ...
        a_hp10, ...
        npad, ...
        half_window_points);


    [~, thir_epica_resolution] = ...
        filtered_moving_std_with_padding( ...
        synthetic_epica_resolution, ...
        b_hp10, ...
        a_hp10, ...
        npad, ...
        half_window_points);


    
    % Thesis Hilbert-amplitude mMCV
    

    [~, hilbert_uniform] = ...
        filtered_hilbert_with_padding( ...
        synthetic_uniform, ...
        b_bp2_10, ...
        a_bp2_10, ...
        npad);


    [~, hilbert_epica_resolution] = ...
        filtered_hilbert_with_padding( ...
        synthetic_epica_resolution, ...
        b_bp2_10, ...
        a_bp2_10, ...
        npad);


    hilbert_uniform = ...
        zscore_columns( ...
        hilbert_uniform);


    hilbert_epica_resolution = ...
        zscore_columns( ...
        hilbert_epica_resolution);

    thir_uniform = ...
        thir_uniform( ...
        output_index, ...
        :);


    thir_epica_resolution = ...
        thir_epica_resolution( ...
        output_index, ...
        :);


    hilbert_uniform = ...
        hilbert_uniform( ...
        output_index, ...
        :);


    hilbert_epica_resolution = ...
        hilbert_epica_resolution( ...
        output_index, ...
        :);

    SYN.thir_uniform( ...
        :, ...
        column_index) = ...
        single( ...
        gaussian_smooth_matrix( ...
        thir_uniform, ...
        opts.output_dt_kyr, ...
        opts.gaussian_window_kyr));


    SYN.thir_epica_resolution( ...
        :, ...
        column_index) = ...
        single( ...
        gaussian_smooth_matrix( ...
        thir_epica_resolution, ...
        opts.output_dt_kyr, ...
        opts.gaussian_window_kyr));


    SYN.hilbert_uniform( ...
        :, ...
        column_index) = ...
        single( ...
        gaussian_smooth_matrix( ...
        hilbert_uniform, ...
        opts.output_dt_kyr, ...
        opts.gaussian_window_kyr));


    SYN.hilbert_epica_resolution( ...
        :, ...
        column_index) = ...
        single( ...
        gaussian_smooth_matrix( ...
        hilbert_epica_resolution, ...
        opts.output_dt_kyr, ...
        opts.gaussian_window_kyr));


end


fprintf( ...
    "Monte Carlo simulations completed.\n");




