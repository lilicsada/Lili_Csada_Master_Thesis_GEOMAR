    NaN;



out = ...
    beast( ...
    y(:), ...
    'start', ...
    0, ...
    'deltat', ...
    dt, ...
    'season', ...
    'none', ...
    'tcp.minmax', ...
    tcp_minmax, ...
    'torder.minmax', ...
    torder_minmax, ...
    'mcmc.seed', ...
    seed, ...
    'mcmc.samples', ...
    mcmc_samples, ...
    'mcmc.burnin', ...
    mcmc_burnin, ...
    'mcmc.chains', ...
    mcmc_chains, ...
    'mcmc.thin', ...
    mcmc_thin, ...
    'print.progress', ...
    false, ...
    'print.param', ...
    false, ...
    'print.warning', ...
    false, ...
    'quiet', ...
    true, ...
    'dump.ci', ...
    false);



if ...
        ~isfield( ...
        out, ...
        'trend')


    return;


end




% MODAL NUMBER OF TREND CHANGEPOINTS

if ...
        isfield( ...
        out.trend, ...
        'ncp_mode') && ...
        ~isempty( ...
        out.trend.ncp_mode)


    tmp = ...
        double( ...
        out.trend.ncp_mode(:));


    tmp = ...
        tmp( ...
        isfinite(tmp));


    if ...
            ~isempty(tmp)


        ncp_mode = ...
            tmp(1);


    end


end



if ...
        ~isfinite( ...
        ncp_mode) && ...
        isfield( ...
        out.trend, ...
        'ncpPr') && ...
        ~isempty( ...
        out.trend.ncpPr)


    ncpPr = ...
        double( ...
        out.trend.ncpPr(:));


    [ ...
        ~, ...
        idx_mode ...
        ] = ...
        max( ...
        ncpPr);


    ncp_mode = ...
        idx_mode - ...
        1;


end



% Do not force a changepoint when BEAST selects zero CP.

if ...
        ~isfinite( ...
        ncp_mode) || ...
        ncp_mode < ...
        1


    return;


end




% PREFERRED CHANGEPOINT EXTRACTION


if ...
        isfield( ...
        out.trend, ...
        'cp') && ...
        ~isempty( ...
        out.trend.cp)


    cp_candidates = ...
        double( ...
        out.trend.cp(:));



    if ...
            isfield( ...
            out.trend, ...
            'cpPr') && ...
            ~isempty( ...
            out.trend.cpPr)


        cp_pr = ...
            double( ...
            out.trend.cpPr(:));


    else


        cp_pr = ...
            nan( ...
            size( ...
            cp_candidates));


    end



    valid = ...
        isfinite( ...
        cp_candidates) & ...
        cp_candidates >= ...
        0 & ...
        cp_candidates <= ...
        age_max;



    if ...
            any(valid)


        cp_candidates = ...
            cp_candidates(valid);



        if ...
                numel(cp_pr) == ...
                numel(valid)


            cp_pr = ...
                cp_pr(valid);


        else


            cp_pr = ...
                nan( ...
                size( ...
                cp_candidates));


        end



        if ...
                any( ...
                isfinite( ...
                cp_pr))


            [ ...
                ~, ...
                best ...
                ] = ...
                max( ...
                cp_pr);


            cp_age = ...
                cp_candidates(best);


        else


            cp_age = ...
                cp_candidates(1);


        end


    end


end




% FALLBACK


if ...
        ~isfinite( ...
        cp_age) && ...
        isfield( ...
        out.trend, ...
        'cpOccPr') && ...
        ~isempty( ...
        out.trend.cpOccPr)


    cp_occ = ...
        double( ...
        out.trend.cpOccPr(:));


    if ...
            numel(cp_occ) == ...
            numel(age)


        [ ...
            ~, ...
            best ...
            ] = ...
            max( ...
            cp_occ);


        cp_age = ...
            age(best);


    end


end


end




