
% CURVED-TREND AUTOCORRELATION-SENSITIVITY TEST
%
% ONE TREND ONLY:
% Flat before 600 kyr BP, followed by a gently curved,
% accelerating increase towards the present.
%
% Fixed noise level:
% signal:noise = 1:0.2
%
% AR(1) autocorrelation values:
% phi = 0, 0.5, 0.7, 0.93
%
% 100 Monte Carlo realisations per autocorrelation level.
%
% Methods:
%   - SiZer
%   - findchangepts
%   - BEAST
%
% Requires:
%   - chpttests.m
%   - Abram/Marron SiZer folder
%   - BEAST installed
%
% Nothing is saved automatically.


clear;
close all;
clc;

rng(1);



% 1. BASIC SETTINGS


dt = ...
    0.5;


age_max = ...
    800;


age = ...
    (0:dt:age_max)';


n = ...
    numel(age);


change_age = ...
    600;




% PROXY-DERIVED PARAMETERS


sigma_proxy = ...
    0.88;


phi_proxy = ...
    0.93;


deltaT = ...
    2 * ...
    sigma_proxy;




% FIXED NOISE LEVEL
%
% Definition:
%
% DeltaT : 2*sigma_noise = 1 : 0.2


noise_ratio = ...
    0.2;


sigma_noise = ...
    noise_ratio * ...
    deltaT / ...
    2;




% AUTOCORRELATION CONDITIONS


phi_values = ...
    [ ...
    0 ...
    0.5 ...
    0.7 ...
    phi_proxy ...
    ];


phi_names = ...
    { ...
    '\phi = 0'
    '\phi = 0.5'
    '\phi = 0.7'
    '\phi = 0.93'
    };


nPhi = ...
    numel( ...
    phi_values);




% MONTE CARLO SETTINGS


nRep = ...
    1000;


burnin = ...
    2000;




% 2. CLEAN CURVED TREND
%
% Flat between 800 and 600 kyr BP.
%
% From 600 kyr BP towards the present:
% gently curved accelerating increase.

clean_trend = ...
    zeros( ...
    size(age));


idx_post = ...
    age <= ...
    change_age;


u = ...
    ( ...
    change_age - ...
    age(idx_post) ...
    ) / ...
    change_age;


% u = 0 at 600 kyr BP
%
% u = 1 at 0 kyr BP


clean_trend(idx_post) = ...
    deltaT * ...
    ( ...
    1 - ...
    cos( ...
    (pi/2) * ...
    u ...
    ) ...
    );




% 3. SIZER AND FINDCHANGEPTS SETTINGS


opts = ...
    struct();


opts.methods = ...
    [ ...
    "sizer" ...
    "findchangepts" ...
    ];




% SIZER


opts.sizer.bandwidth_min = ...
    60;


opts.sizer.bandwidth_max = ...
    100;


opts.sizer.n_bandwidths = ...
    41;


opts.sizer.x_step = ...
    1.0;


opts.sizer.alpha = ...
    0.10;


opts.sizer.simflag = ...
    2;


opts.sizer.iregtdist = ...
    0;


opts.sizer.endpoint_flag = ...
    0;


opts.sizer.boundary_adjustment = ...
    0;


opts.sizer.onset_mode = ...
    "all";


opts.sizer.min_run_kyr = ...
    40;


opts.sizer.edge_ignore_kyr = ...
    0;


opts.sizer.cluster_gap_kyr = ...
    35;


opts.sizer.min_bw_fraction = ...
    0.80;


opts.sizer.uncertainty_mode = ...
    "iqr";




% FINDCHANGEPTS


opts.findchangepts.smooth_kyr = ...
    0;


opts.findchangepts.max_num_changes = ...
    1;




% 4. BEAST SETTINGS


if ...
        exist( ...
        'beast', ...
        'file') ~= ...
        2


    error( ...
        'BEAST was not found on the MATLAB path.');


end



beast_tcp_minmax = ...
    [0 1];


beast_torder_minmax = ...
    [0 1];


beast_mcmc_samples = ...
    4000;


beast_mcmc_burnin = ...
    1000;


beast_mcmc_chains = ...
    2;


beast_mcmc_thin = ...
    5;




% 5. GENERATE PAIRED RANDOM INNOVATIONS
%
% The same Gaussian innovations are used for every phi value.
%
% Only the autocorrelation changes.
%
% This isolates the effect of AR(1) memory from differences
% between random noise realisations.


innovations = ...
    randn( ...
    n + ...
    burnin, ...
    nRep);




% 6. STORAGE

cp_sizer = ...
    nan( ...
    nRep, ...
    nPhi);


cp_find = ...
    nan( ...
    nRep, ...
    nPhi);


cp_beast = ...
    nan( ...
    nRep, ...
    nPhi);



sizer_success = ...
    false( ...
    nRep, ...
    nPhi);


find_success = ...
    false( ...
    nRep, ...
    nPhi);


beast_success = ...
    false( ...
    nRep, ...
    nPhi);



beast_ncp_mode = ...
    nan( ...
    nRep, ...
    nPhi);



example_series = ...
    nan( ...
    n, ...
    nPhi);



realised_phi = ...
    nan( ...
    nRep, ...
    nPhi);




% 7. MONTE CARLO LOOP


fprintf('\n');

fprintf( ...
    'CURVED-TREND AUTOCORRELATION-SENSITIVITY TEST\n');


fprintf( ...
    'True onset = %.1f kyr BP\n', ...
    change_age);


fprintf( ...
    'Signal:noise = 1:%.1f\n', ...
    noise_ratio);


fprintf( ...
    'Realisations = %d per phi value\n\n', ...
    nRep);



for q = 1:nPhi


    phi = ...
        phi_values(q);


    fprintf( ...
        'phi = %.6f\n', ...
        phi);



    for r = 1:nRep



        
        % GENERATE AR(1) NOISE
        

        noise_long = ...
            zeros( ...
            n + ...
            burnin, ...
            1);



        for k = 2:(n + burnin)


            noise_long(k) = ...
                phi * ...
                noise_long(k-1) + ...
                innovations(k,r);


        end



        noise_raw = ...
            noise_long( ...
            burnin+1:end);



       
        % STANDARDISE AND RESCALE
        %
        % All phi conditions have the same final standard
        % deviation. Therefore only temporal persistence changes.
       

        noise = ...
            ( ...
            noise_raw - ...
            mean( ...
            noise_raw, ...
            'omitnan') ...
            ) ./ ...
            std( ...
            noise_raw, ...
            'omitnan');


        noise = ...
            sigma_noise * ...
            noise;



       
        % CALCULATE REALISED LAG-1 AUTOCORRELATION
       

        noise_centred = ...
            noise - ...
            mean( ...
            noise, ...
            'omitnan');


        realised_phi(r,q) = ...
            corr( ...
            noise_centred(1:end-1), ...
            noise_centred(2:end), ...
            'Rows', ...
            'complete');



        
        % SYNTHETIC SERIES
       

        synthetic_raw = ...
            clean_trend + ...
            noise;


        synthetic_z = ...
            ( ...
            synthetic_raw - ...
            mean( ...
            synthetic_raw, ...
            'omitnan') ...
            ) ./ ...
            std( ...
            synthetic_raw, ...
            'omitnan');



        if ...
                r == ...
                1


            example_series(:,q) = ...
                synthetic_raw;


        end



        
        % SIZER AND FINDCHANGEPTS
       

        try


            out = ...
                chpttests( ...
                age, ...
                synthetic_z, ...
                opts);



            cp_sizer(r,q) = ...
                out.sizer.cp_age;


            cp_find(r,q) = ...
                out.findchangepts.cp_age;



            sizer_success(r,q) = ...
                out.sizer.run_successful;


            find_success(r,q) = ...
                out.findchangepts.run_successful;



        catch ME


            if ...
                    r == ...
                    1


                fprintf( ...
                    'SiZer/findchangepts error: %s\n', ...
                    ME.message);


            end


        end



        
        % BEAST
       

        try


            beast_seed = ...
                ( ...
                q - ...
                1 ...
                ) * ...
                nRep + ...
                r;



            [ ...
                cp_beast(r,q), ...
                beast_ncp_mode(r,q) ...
                ] = ...
                run_beast_once( ...
                synthetic_z, ...
                age, ...
                dt, ...
                age_max, ...
                beast_tcp_minmax, ...
                beast_torder_minmax, ...
                beast_seed, ...
                beast_mcmc_samples, ...
                beast_mcmc_burnin, ...
                beast_mcmc_chains, ...
                beast_mcmc_thin);



            beast_success(r,q) = ...
                true;



        catch ME


            if ...
                    r == ...
                    1


                fprintf( ...
                    'BEAST error: %s\n', ...
                    ME.message);


            end


        end



       
        % PROGRESS
       

        if ...
                mod( ...
                r, ...
                10) == ...
                0


            fprintf( ...
                '  %d / %d\n', ...
                r, ...
                nRep);


        end


    end


end



fprintf( ...
    '\nAll calculations completed.\n');




% 8. REALISED AUTOCORRELATION SUMMARY


