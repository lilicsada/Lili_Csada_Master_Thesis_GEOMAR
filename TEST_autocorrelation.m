% LOCAL FUNCTION:
% RUN BEAST ONCE

function [ ...
    cp_age, ...
    ncp_mode ...
    ] = ...
    run_beast_once( ...
    y, ...
    age, ...
    dt, ...
    age_max, ...
    tcp_minmax, ...
    torder_minmax, ...
    seed, ...
    mcmc_samples, ...
    mcmc_burnin, ...
    mcmc_chains, ...
    mcmc_thin)


