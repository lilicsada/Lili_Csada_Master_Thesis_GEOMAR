
% Synthetic mMCV test: trend-geometry sensitivity

% Fixed synthetic settings:
%   age range          = 0-800 kyr BP
%   true transition    = 600 kyr BP
%   temporal spacing   = 0.5 kyr
%   signal:noise       = 1:0.2
%   proxy AR(1) phi    = 0.93004
%
% Methods:
%   1. Original Abram / Marron SiZer via chpttests.m
%   2. MATLAB findchangepts via chpttests.m
%   3. BEAST
%


clear;
close all;
clc;

rng(1); 


% 1. SYNTHETIC DATA SETTINGS
dt = 0.5;                     % kyr
age_max = 800;                % kyr BP
age = (0:dt:age_max)';        % ascending 0 -> 800
n = numel(age);
change_age = 600;             % prescribed transition age, kyr BP

% Proxy-derived parameters
sigma_proxy = 0.88047;
phi_proxy = 0.93004;

% Total imposed signal change
deltaT = 2 * sigma_proxy;

% Weak-noise experiment:
% DeltaT : 2*sigma_noise = 1 : 0.2
noise_ratio = 0.2;
sigma_noise = noise_ratio * deltaT / 2;

burnin = 2000;
nRep = 10;



% 2. SHARED SIZER AND FINDCHANGEPTS SETTINGS


if exist('chpttests', 'file') ~= 2
    error(['chpttests.m was not found on the MATLAB path. ' ...
           'Place it beside this script or add its folder to the path.']);
end

opts = struct();

opts.methods = ...
    [ ...
    "sizer" ...
    "findchangepts" ...
    ];


% SiZer: final Abram / Marron setup

opts.sizer.bandwidth_min = 60;
opts.sizer.bandwidth_max = 100;
opts.sizer.n_bandwidths = 41;
opts.sizer.x_step = 1.0;
opts.sizer.alpha = 0.10;
opts.sizer.simflag = 2;
opts.sizer.iregtdist = 0;
opts.sizer.endpoint_flag = 0;
opts.sizer.boundary_adjustment = 0;

opts.sizer.onset_mode = "all";
opts.sizer.min_run_kyr = 40;
opts.sizer.edge_ignore_kyr = 0;
opts.sizer.cluster_gap_kyr = 35;
opts.sizer.min_bw_fraction = 0.80;
opts.sizer.uncertainty_mode = "iqr";

%% ------------------------------------------------------------
% findchangepts
%% ------------------------------------------------------------

opts.findchangepts.smooth_kyr = 0;
opts.findchangepts.max_num_changes = 1;

%% ============================================================
% 3. BEAST SETTINGS
%% ============================================================

if exist('beast', 'file') ~= 2
    error(['The BEAST function was not found on the MATLAB path. ' ...
           'Add the BEAST folder before running this script.']);
end

beast_tcp_minmax = [0 1];
beast_torder_minmax = [0 1];

beast_mcmc_samples = 4000;
beast_mcmc_burnin = 1000;
beast_mcmc_chains = 2;
beast_mcmc_thin = 5;

%% ============================================================
% 4. BUILD SIX CLEAN TREND GEOMETRIES
%% ============================================================

trend_names = {
    'Flat'
    'Abrupt jump'
    'Flat to linear increase'
    'Flat to curved increase'
    'Linear decrease to increase'
    'Curved decrease to increase'
    };

roman_labels = {'i','ii','iii','iv','v','vi'};

nTrend = numel(trend_names);
clean_trend = zeros(n, nTrend);

older = age >= change_age;
younger = age <= change_age;

% Younger-side coordinate:
% u = 0 at 600 kyr BP
% u = 1 at the present
u_young = (change_age - age(younger)) / change_age;

% Older-side coordinate:
% v = 0 at 600 kyr BP
% v = 1 at 800 kyr BP
v_old = (age(older) - change_age) / (age_max - change_age);

% i) Flat
clean_trend(:,1) = 0;

% ii) Abrupt jump at 600 kyr BP
tmp = zeros(n,1);
tmp(younger) = deltaT;
clean_trend(:,2) = tmp;

% iii) Flat, then linear increase towards the present
tmp = zeros(n,1);
tmp(younger) = deltaT * u_young;
clean_trend(:,3) = tmp;

% iv) Flat, then curved accelerating increase towards the present
tmp = zeros(n,1);
tmp(younger) = deltaT * ...
    (1 - cos((pi/2) * u_young));
clean_trend(:,4) = tmp;

% v) Linear decrease to 600 kyr BP, then linear increase
tmp = zeros(n,1);
tmp(older) = deltaT * v_old;
tmp(younger) = deltaT * u_young;
clean_trend(:,5) = tmp;

% vi) Curved decrease to 600 kyr BP, then curved increase
tmp = zeros(n,1);
tmp(older) = deltaT * ...
    (1 - cos((pi/2) * v_old));
tmp(younger) = deltaT * ...
    (1 - cos((pi/2) * u_young));
clean_trend(:,6) = tmp;

%% ============================================================
% 5. GENERATE THE SAME 100 NOISE REALISATIONS FOR ALL TRENDS
%% ============================================================

noise_all = nan(n, nRep);

for r = 1:nRep

    noise_long = zeros(n + burnin, 1);

    for k = 2:(n + burnin)
        noise_long(k) = ...
            phi_proxy * noise_long(k-1) + randn;
    end

    noise_raw = noise_long(burnin+1:end);

    noise_standardised = ...
        (noise_raw - mean(noise_raw, 'omitnan')) ./ ...
        std(noise_raw, 'omitnan');

    noise_all(:,r) = ...
        sigma_noise * noise_standardised;

end


% 6. OUTPUT STORAGE


cp_sizer = nan(nRep, nTrend);
cp_findchangepts = nan(nRep, nTrend);
cp_beast = nan(nRep, nTrend);

sizer_success = false(nRep, nTrend);
findcp_success = false(nRep, nTrend);
beast_success = false(nRep, nTrend);

beast_ncp_mode = nan(nRep, nTrend);

% Store the first noisy realisation for the left-hand panels
example_series = nan(n, nTrend);


% 7. MONTE CARLO LOOP


fprintf('\n============================================================\n');
fprintf('TREND-GEOMETRY MONTE CARLO TEST\n');
fprintf('============================================================\n');
fprintf('Realisations per trend: %d\n', nRep);
fprintf('Signal:noise = 1:%.1f\n', noise_ratio);
fprintf('Noise sigma = %.6f\n', sigma_noise);
fprintf('Proxy AR(1) phi = %.6f\n', phi_proxy);
fprintf('True transition age = %.1f kyr BP\n', change_age);
fprintf('============================================================\n\n');

for j = 1:nTrend

    fprintf('Trend %d/%d: %s\n', ...
        j, nTrend, trend_names{j});

    for r = 1:nRep

        
        % Synthetic proxy
        

        synthetic_raw = ...
            clean_trend(:,j) + noise_all(:,r);

        synthetic_z = ...
            (synthetic_raw - mean(synthetic_raw, 'omitnan')) ./ ...
            std(synthetic_raw, 'omitnan');

        if r == 1
            example_series(:,j) = synthetic_raw;
        end

        
        % 1-2. SIZER AND FINDCHANGEPTS VIA CHPTTESTS
        

        try

            out = ...
                chpttests( ...
                age, ...
                synthetic_z, ...
                opts);

            cp_sizer(r,j) = ...
                out.sizer.cp_age;

            cp_findchangepts(r,j) = ...
                out.findchangepts.cp_age;

            sizer_success(r,j) = ...
                out.sizer.run_successful;

            findcp_success(r,j) = ...
                out.findchangepts.run_successful;

        catch ME

            if r == 1
                fprintf( ...
                    '  SiZer/findchangepts error: %s\n', ...
                    ME.message);
            end

        end

        
        % 3. BEAST
       

        try

            beast_seed = ...
                (j - 1) * nRep + r;

            [ ...
                cp_beast(r,j), ...
                beast_ncp_mode(r,j) ...
                ] = ...
                run_beast_once( ...
                synthetic_z, ...
                age, ...
                dt, ...
                age_max, ...
                beast_tcp_minmax, ...
                beast_torder_minmax, ...
                beast_seed, ...
                beast_mcmc_samples, ...
                beast_mcmc_burnin, ...
                beast_mcmc_chains, ...
                beast_mcmc_thin);

            beast_success(r,j) = true;

        catch ME

            if r == 1
                fprintf('  BEAST error: %s\n', ME.message);
            end

        end

        
        % Progress
       

        if mod(r,10) == 0
            fprintf('  %d / %d complete\n', r, nRep);
        end

    end

end

fprintf('\nAll Monte Carlo calculations completed.\n');


% 8. SUMMARY TABLE

Summary = build_summary_table( ...
    trend_names, ...
    cp_sizer, ...
    cp_findchangepts, ...
    cp_beast, ...
    change_age, ...
    nRep);

disp(' ');
disp('MONTE CARLO SUMMARY');
disp(Summary);


% 9. PRINT BEAST MODEL-SELECTION SUMMARY

fprintf('\nBEAST MODEL-SELECTION SUMMARY\n');
fprintf('-----------------------------------------------\n');

for j = 1:nTrend

    valid = beast_success(:,j) & ...
        isfinite(beast_ncp_mode(:,j));

    n_valid = sum(valid);

    if n_valid == 0

        fprintf('%-32s : no valid BEAST runs\n', ...
            trend_names{j});

    else

        pct_0 = 100 * ...
            sum(beast_ncp_mode(valid,j) == 0) / ...
            n_valid;

        pct_1 = 100 * ...
            sum(beast_ncp_mode(valid,j) >= 1) / ...
            n_valid;

        fprintf( ...
            '%-32s : 0 CP = %5.1f%%; 1 CP = %5.1f%%\n', ...
            trend_names{j}, ...
            pct_0, ...
            pct_1);

    end

end


% 10. FIGURE SETTINGS


font_name = 'Cambria Math';

col_sizer = [0.05 0.15 0.95];
col_find = [1.00 0.45 0.00];
col_beast = [0.72 0.00 0.88];

% Common relative-error limit for all three method columns
all_error = [
    cp_sizer(:) - change_age
    cp_findchangepts(:) - change_age
    cp_beast(:) - change_age
    ];

all_error = all_error(isfinite(all_error));

if isempty(all_error)

    error_limit = 100;

else

    q95_abs = local_percentile( ...
