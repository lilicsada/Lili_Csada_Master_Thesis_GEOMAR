fig = figure( ...
    'Color', ...
    'w', ...
    'Units', ...
    'pixels', ...
    'Position', ...
    [50 40 1250 820], ...
    'Renderer', ...
    'painters');

left_margin = 0.065;
right_margin = 0.025;
top_margin = 0.055;
bottom_margin = 0.070;

row_gap = 0.008;
column_gap = 0.014;

column_widths = [0.40 0.18 0.18 0.18];

usable_width = ...
    1 - left_margin - right_margin - ...
    3 * column_gap;

column_widths = ...
    column_widths / sum(column_widths) * ...
    usable_width;

x0 = nan(1,4);
x0(1) = left_margin;

for c = 2:4
    x0(c) = ...
        x0(c-1) + ...
        column_widths(c-1) + ...
        column_gap;
end

panel_height = ...
    (1 - top_margin - bottom_margin - ...
    (nTrend - 1) * row_gap) / ...
    nTrend;

% Common y limits for example synthetic series
all_example = [
    example_series(:)
    clean_trend(:)
    ];

all_example = ...
    all_example(isfinite(all_example));

y_min = min(all_example);
y_max = max(all_example);

y_pad = 0.06 * (y_max - y_min);

if y_pad == 0
    y_pad = 1;
end

example_ylim = ...
    [y_min - y_pad, y_max + y_pad];


% 12. DRAW THE FOUR-COLUMN FIGURE


for j = 1:nTrend

    y0 = ...
        1 - top_margin - ...
        j * panel_height - ...
        (j - 1) * row_gap;

    
    % Column 1: synthetic example
    

    ax1 = axes( ...
