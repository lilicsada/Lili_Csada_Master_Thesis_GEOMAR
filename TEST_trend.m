% LOCAL FUNCTION:
% PERCENTILE WITHOUT REQUIRING PRCTILE


function v = ...
    local_percentile( ...
    x, ...
    p)

    x = ...
        sort( ...
        x( ...
        isfinite(x)));

    if isempty(x)

        v = NaN;
        return;

    end

    x = x(:);
    n = numel(x);

    if n == 1

        v = x;
        return;

    end

    position = ...
        1 + ...
        (p / 100) * ...
        (n - 1);

    lo = floor(position);
    hi = ceil(position);

    if lo == hi

        v = x(lo);

    else

        weight = ...
            position - lo;

        v = ...
            (1 - weight) * ...
            x(lo) + ...
            weight * ...
            x(hi);

    end

end
