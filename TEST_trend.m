% LOCAL FUNCTION:
% RUN BEAST ONCE


function [cp_age, ncp_mode] = ...
    run_beast_once( ...
    y, ...
    age, ...
    dt, ...
    age_max, ...
    tcp_minmax, ...
    torder_minmax, ...
    seed, ...
    mcmc_samples, ...
    mcmc_burnin, ...
    mcmc_chains, ...
    mcmc_thin)

    cp_age = NaN;
    ncp_mode = NaN;

    y = y(:);

    out = beast( ...
        y, ...
        'start', ...
        0, ...
        'deltat', ...
        dt, ...
        'season', ...
        'none', ...
        'tcp.minmax', ...
        tcp_minmax, ...
        'torder.minmax', ...
        torder_minmax, ...
        'mcmc.seed', ...
        seed, ...
        'mcmc.samples', ...
        mcmc_samples, ...
        'mcmc.burnin', ...
        mcmc_burnin, ...
        'mcmc.chains', ...
        mcmc_chains, ...
        'mcmc.thin', ...
        mcmc_thin, ...
        'print.progress', ...
        false, ...
        'print.options', ...
        false);

    if ~isfield(out,'trend')
        return;
    end

    %% Determine posterior modal number of changepoints

    if ...
            isfield(out.trend,'ncp_mode') && ...
            ~isempty(out.trend.ncp_mode)

        tmp = ...
            double(out.trend.ncp_mode(:));

        tmp = ...
            tmp(isfinite(tmp));

        if ~isempty(tmp)
            ncp_mode = tmp(1);
        end

    end

    if ...
            ~isfinite(ncp_mode) && ...
            isfield(out.trend,'ncpPr') && ...
            ~isempty(out.trend.ncpPr)

        ncpPr = ...
            double(out.trend.ncpPr(:));

        [~, idx_mode] = ...
            max(ncpPr);

        ncp_mode = ...
            idx_mode - 1;

    end

    %% Only retain a CP age when the modal model contains one CP

    if ...
            ~isfinite(ncp_mode) || ...
            ncp_mode < 1

        return;

    end

    %% Preferred extraction: reported trend CP candidates

    if ...
            isfield(out.trend,'cp') && ...
            ~isempty(out.trend.cp)

        cp_candidates = ...
            double(out.trend.cp(:));

        if ...
                isfield(out.trend,'cpPr') && ...
                ~isempty(out.trend.cpPr)

            cp_pr = ...
                double(out.trend.cpPr(:));

        else

            cp_pr = ...
                nan(size(cp_candidates));

        end

        valid = ...
            isfinite(cp_candidates) & ...
            cp_candidates >= 0 & ...
            cp_candidates <= age_max;

        if any(valid)

            cp_candidates = ...
                cp_candidates(valid);

            cp_pr = ...
                cp_pr(valid);

            if any(isfinite(cp_pr))

                [~, best] = ...
                    max(cp_pr);

                cp_age = ...
                    cp_candidates(best);

            else

                cp_age = ...
                    cp_candidates(1);

            end

        end

    end

    %% Fallback: maximum CP occurrence probability

    if ...
            ~isfinite(cp_age) && ...
            isfield(out.trend,'cpOccPr') && ...
            ~isempty(out.trend.cpOccPr)

        cp_occ = ...
            double(out.trend.cpOccPr(:));

        if numel(cp_occ) == numel(age)

            [~, best] = ...
                max(cp_occ);

            cp_age = ...
                age(best);

        end

    end

end


% LOCAL FUNCTION:
% BUILD SUMMARY TABLE


function Summary = ...
    build_summary_table( ...
    trend_names, ...
    cp_sizer, ...
    cp_find, ...
    cp_beast, ...
    true_age, ...
    nRep)

    method_names = {
        'SiZer'
        'findchangepts'
        'BEAST'
        };

    method_data = {
        cp_sizer
        cp_find
        cp_beast
        };

    nTrend = numel(trend_names);
    nMethod = numel(method_names);
    nRow = nTrend * nMethod;

    Trend = strings(nRow,1);
    Method = strings(nRow,1);

    Detections = nan(nRow,1);
    DetectionRate_pct = nan(nRow,1);

    MedianAge_kyr = nan(nRow,1);

    Q25_kyr = nan(nRow,1);
    Q75_kyr = nan(nRow,1);

    P05_kyr = nan(nRow,1);
    P95_kyr = nan(nRow,1);

    MedianError_kyr = nan(nRow,1);

    row = 0;

    for j = 1:nTrend

        for m = 1:nMethod

            row = row + 1;

            cp = ...
                method_data{m}(:,j);

            cp = ...
                cp(isfinite(cp));

            Trend(row) = ...
                string(trend_names{j});

            Method(row) = ...
                string(method_names{m});

            Detections(row) = ...
                numel(cp);

            DetectionRate_pct(row) = ...
                100 * numel(cp) / nRep;

            if ~isempty(cp)

                MedianAge_kyr(row) = ...
                    median(cp,'omitnan');

                Q25_kyr(row) = ...
                    local_percentile(cp,25);

                Q75_kyr(row) = ...
                    local_percentile(cp,75);

                P05_kyr(row) = ...
                    local_percentile(cp,5);

                P95_kyr(row) = ...
                    local_percentile(cp,95);

                if j > 1

                    MedianError_kyr(row) = ...
                        median( ...
                        cp - true_age, ...
                        'omitnan');

                end

            end

        end

    end

    Summary = table( ...
        Trend, ...
        Method, ...
        Detections, ...
        DetectionRate_pct, ...
        MedianAge_kyr, ...
        Q25_kyr, ...
        Q75_kyr, ...
        P05_kyr, ...
        P95_kyr, ...
        MedianError_kyr);

end


% LOCAL FUNCTION:
% DRAW ONE METHOD DISTRIBUTION


