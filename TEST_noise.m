    phi_proxy);


fprintf( ...
    'Realisations = %d per noise level\n\n', ...
    nRep);



for q = 1:nNoise


    ratio = ...
        noise_ratios(q);


    sigma_noise = ...
        ratio * ...
        deltaT / ...
        2;


    fprintf( ...
        'Signal:noise = 1:%.1f\n', ...
        ratio);



    for r = 1:nRep



        
        % SYNTHETIC SERIES
       

        noise = ...
            sigma_noise * ...
            base_noise(:,r);


        synthetic_raw = ...
            clean_trend + ...
            noise;


        synthetic_z = ...
            ( ...
            synthetic_raw - ...
            mean( ...
            synthetic_raw, ...
            'omitnan') ...
            ) ./ ...
            std( ...
            synthetic_raw, ...
            'omitnan');


        if r == 1


            example_series(:,q) = ...
                synthetic_raw;


        end



        
        % SIZER + FINDCHANGEPTS
        

        out = ...
            chpttests( ...
            age, ...
            synthetic_z, ...
            opts);



        cp_sizer(r,q) = ...
            out.sizer.cp_age;


        cp_find(r,q) = ...
            out.findchangepts.cp_age;



        sizer_success(r,q) = ...
            out.sizer.run_successful;


        find_success(r,q) = ...
            out.findchangepts.run_successful;



        
        % BEAST
        

        try


            beast_seed = ...
                ( ...
                q - ...
                1 ...
                ) * ...
                nRep + ...
                r;



            [ ...
                cp_beast(r,q), ...
                beast_ncp_mode(r,q) ...
                ] = ...
                run_beast_once( ...
                synthetic_z, ...
                age, ...
                dt, ...
                age_max, ...
                beast_tcp_minmax, ...
                beast_torder_minmax, ...
                beast_seed, ...
                beast_mcmc_samples, ...
                beast_mcmc_burnin, ...
                beast_mcmc_chains, ...
                beast_mcmc_thin);



            beast_success(r,q) = ...
                true;



        catch ME


            if r == 1


                fprintf( ...
                    'BEAST error: %s\n', ...
                    ME.message);


            end


        end



       
        % PROGRESS
        

        if ...
                mod( ...
                r, ...
                10) == ...
                0


            fprintf( ...
                '  %d / %d\n', ...
                r, ...
                nRep);


        end


    end


end


fprintf( ...
    '\nAll calculations completed.\n');




