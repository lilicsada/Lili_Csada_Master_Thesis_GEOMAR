
% CURVED-TREND NOISE-SENSITIVITY TEST
%
% ONE TREND ONLY:h
% flat before 600 kyr BP, then a gently curved accelerating
% increase towards the present.
%
% Noise levels:
% signal:noise = 1:0, 1:0.2, 1:0.5, 1:1.0, 1:1.5
%
% 100 Monte Carlo realisations per noise level.
%
% Requires:
%   chpttests.m
%   original Abram/Marron SiZer folder
%   BEAST installed
%


clear;
close all;
clc;

rng(1);


% 1. SETTINGS

dt = 0.5;

age_max = 800;

age = ...
    (0:dt:age_max)';


change_age = 600;


sigma_proxy = ...
    0.88047;


phi_proxy = ...
    0.93004;


deltaT = ...
    2 * sigma_proxy;


% Definition:
%
% deltaT : 2*sigma_noise = 1 : noise_ratio

noise_ratios = ...
    [ ...
    0 ...
    0.2 ...
    0.5 ...
    1.0 ...
    1.5 ...
    ];


nNoise = ...
    numel( ...
    noise_ratios);


nRep = ...
    1000;


burnin = ...
    2000;




% 2. ONE CLEAN CURVED TREND ONLY
%
% Flat between 800 and 600 kyr BP.
%
% From 600 kyr BP towards the present:
% gently curved accelerating increase.


clean_trend = ...
    zeros( ...
    size(age));


idx_post = ...
    age <= ...
    change_age;


u = ...
    ( ...
    change_age - ...
    age(idx_post) ...
    ) / ...
    change_age;


% u = 0 at 600 kyr BP
%
% u = 1 at 0 kyr BP


clean_trend(idx_post) = ...
    deltaT * ...
    ( ...
    1 - ...
    cos( ...
    (pi/2) * ...
    u) ...
    );




% 3. EXACT SIZER AND FINDCHANGEPTS SETTINGS


opts = ...
    struct();


opts.methods = ...
    [ ...
    "sizer" ...
    "findchangepts" ...
    ];




% SIZER


opts.sizer.bandwidth_min = ...
    60;


opts.sizer.bandwidth_max = ...
    100;


opts.sizer.n_bandwidths = ...
    41;


opts.sizer.x_step = ...
    1.0;


opts.sizer.alpha = ...
    0.10;


opts.sizer.simflag = ...
    2;


opts.sizer.iregtdist = ...
    0;


opts.sizer.endpoint_flag = ...
    0;


opts.sizer.boundary_adjustment = ...
    0;


opts.sizer.onset_mode = ...
    "all";


opts.sizer.min_run_kyr = ...
    40;


opts.sizer.edge_ignore_kyr = ...
    0;


opts.sizer.cluster_gap_kyr = ...
    35;


opts.sizer.min_bw_fraction = ...
    0.80;


opts.sizer.uncertainty_mode = ...
    "iqr";




% FINDCHANGEPTS


opts.findchangepts.smooth_kyr = ...
    0;


opts.findchangepts.max_num_changes = ...
    1;




% 4. BEAST SETTINGS


if ...
        exist( ...
        'beast', ...
        'file') ~= ...
        2


    error( ...
        'BEAST was not found on the MATLAB path.');


end


beast_tcp_minmax = ...
    [0 1];


beast_torder_minmax = ...
    [0 1];


beast_mcmc_samples = ...
    4000;


beast_mcmc_burnin = ...
    1000;


beast_mcmc_chains = ...
    2;


beast_mcmc_thin = ...
    5;




% 5. GENERATE THE SAME 100 BASE AR(1) REALISATIONS
%
% The same AR(1) noise patterns are used at all noise levels.
%
% Only their amplitude changes.

n = ...
    numel(age);


base_noise = ...
    nan( ...
    n, ...
    nRep);


for r = 1:nRep


    noise_long = ...
        zeros( ...
        n + ...
        burnin, ...
        1);


    for k = 2:(n + burnin)


        noise_long(k) = ...
            phi_proxy * ...
            noise_long(k-1) + ...
            randn;


    end


    noise_raw = ...
        noise_long( ...
        burnin+1:end);


    base_noise(:,r) = ...
        ( ...
        noise_raw - ...
        mean( ...
        noise_raw, ...
        'omitnan') ...
        ) ./ ...
        std( ...
        noise_raw, ...
        'omitnan');


end




% 6. STORAGE


cp_sizer = ...
    nan( ...
    nRep, ...
    nNoise);


cp_find = ...
    nan( ...
    nRep, ...
    nNoise);


cp_beast = ...
    nan( ...
    nRep, ...
    nNoise);



sizer_success = ...
    false( ...
    nRep, ...
    nNoise);


find_success = ...
    false( ...
    nRep, ...
    nNoise);


beast_success = ...
    false( ...
    nRep, ...
    nNoise);



beast_ncp_mode = ...
    nan( ...
    nRep, ...
    nNoise);



example_series = ...
    nan( ...
    n, ...
    nNoise);




% 7. MONTE CARLO LOOP

fprintf( ...
    '\nCURVED-TREND NOISE-SENSITIVITY TEST\n');


fprintf( ...
