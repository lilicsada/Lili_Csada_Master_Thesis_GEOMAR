%% SYNTHETIC EPICA RESOLUTION TEST
% Comparison of:
%   1. Thirumalai-style <10 kyr rolling-standard-deviation metric
%   2. Thesis-style 2--10 kyr Hilbert-amplitude metric
%
% Experimental design:
%
%   1. Generate stationary AR(1) records on a uniform 100-year grid.
%
%   2. Standardise every AR(1) realisation separately and scale it to the
%      EPICA-derived residual standard deviation.
%
%   3. Create two versions of every realisation:
%
%      Uniform control:
%         100-year record
%         -> PCHIP interpolation to 250-, 500-, or 750-year grid
%
%      EPICA-resolution record:
%         100-year record
%         -> sampling at the original EPICA observation ages
%         -> PCHIP interpolation to 250-, 500-, or 750-year grid
%
%   4. Apply both mMCV definitions only after the control and degraded
%      records have been placed on the same target grid.
%
%   5. Smooth each resulting mMCV curve using a 100-kyr Gaussian window.
%
%   6. Calculate percentage bias separately for each paired realisation:
%
%      100 * (EPICA-resolution - uniform control) / uniform control
%
%   7. Plot:
%      - ensemble mean;
%      - 5th--95th percentile range.

clear;
close all;
clc;


% 1. SETTINGS

opts = struct();

% EPICA input file.
opts.epica_file = "Epica_deuterium.txt";

% EPICA age interval used.
opts.age_min_kyr = 0;
opts.age_max_kyr = 801;

% Original resolution of every synthetic record.
opts.base_dt_kyr = 0.10;          % 100 years

% Target analysis grids.
opts.test_dt_kyr = [0.25, 0.50, 0.75];

% Common grid used only for ensemble storage and plotting.
opts.output_dt_kyr = 1.0;

% Interpolation.
opts.interp_method = "pchip";

% Filtering.
opts.filter_order = 4;
opts.pad_kyr = 10;

% Thirumalai-style definition.
opts.thirumalai_cutoff_kyr = 10;
opts.rolling_window_kyr = 2;

% Thesis-style Hilbert definition.
opts.hilbert_lower_period_kyr = 2;
opts.hilbert_upper_period_kyr = 10;

% Long-term smoothing.
opts.trend_window_kyr = 100;

% EPICA residual calculation for AR(1) parameter estimation.
opts.parameter_smooth_kyr = 100;

% AR(1) burn-in.
opts.burn_in_steps = 2000;

% Monte Carlo experiment.
%
% Use 100 initially to check that the code runs correctly.
% Change to 10000 for the final analysis.
opts.n_realizations = 10000;

% Number of realisations processed simultaneously.
opts.chunk_size = 50;

% Reproducible random-number sequence.
opts.random_seed = 20260718;

% Ensemble range.
opts.lower_percentile = 5;
opts.upper_percentile = 95;

% Numerical summary interval.
opts.summary_interval_kyr = [600, 750];


% 2. FIGURE SETTINGS

opts.font_name = "Cambria Math";

opts.axis_font_size = 17;
opts.title_font_size = 18;
opts.label_font_size = 18;
opts.legend_font_size = 14;
opts.panel_font_size = 18;

opts.background_colour = [0.975, 0.935, 0.945];
opts.grid_colour = [1, 1, 1];
opts.grid_alpha = 0.30;

opts.line_width = 1.60;

control_colour = [0.15, 0.40, 0.80];
epica_colour = [0.85, 0.25, 0.25];

bias_colours = [ ...
    0.15, 0.40, 0.80; ...
    0.85, 0.25, 0.25; ...
    0.20, 0.60, 0.35];

% 3. READ THE EPICA RECORD

[age_obs, deltaD_obs] = read_epica_record( ...
    opts.epica_file, ...
    opts.age_min_kyr, ...
    opts.age_max_kyr);

fprintf("\n============================================================\n");
fprintf("EPICA RESOLUTION TEST\n");
fprintf("============================================================\n");
fprintf("Number of EPICA observations: %d\n", numel(age_obs));
fprintf("EPICA age range: %.2f--%.2f kyr BP\n", ...
    min(age_obs), max(age_obs));


% 4. CREATE THE UNIFORM 100-YEAR BASE GRID


age_base_start = ...
    ceil(max(opts.age_min_kyr, min(age_obs)) / opts.base_dt_kyr) ...
    * opts.base_dt_kyr;

age_base_end = ...
    floor(min(opts.age_max_kyr, max(age_obs)) / opts.base_dt_kyr) ...
    * opts.base_dt_kyr;

age_base = ...
    (age_base_start:opts.base_dt_kyr:age_base_end)';

% Restrict EPICA observation ages to the base-grid interval.
keep_obs = ...
    age_obs >= age_base(1) ...
    & age_obs <= age_base(end);

age_obs = age_obs(keep_obs);
deltaD_obs = deltaD_obs(keep_obs);

% Interpolate observed EPICA onto the 100-year grid.
%
% This interpolated EPICA record is used only to estimate phi and
% sigma_proxy. It is not used as a synthetic control.
deltaD_base = interp1( ...
    age_obs, ...
    deltaD_obs, ...
    age_base, ...
    opts.interp_method);


% 5. CREATE THE COMMON OUTPUT GRID


age_output_start = ...
    ceil(age_base(1) / opts.output_dt_kyr) ...
    * opts.output_dt_kyr;

age_output_end = ...
    floor(age_base(end) / opts.output_dt_kyr) ...
    * opts.output_dt_kyr;

age_output = ...
    (age_output_start:opts.output_dt_kyr:age_output_end)';


% 6. ESTIMATE EPICA-DERIVED AR(1) PARAMETERS


% Remove the long-term EPICA background.
EPICA_long_term = gaussian_smooth_matrix( ...
    deltaD_base, ...
    opts.base_dt_kyr, ...
    opts.parameter_smooth_kyr);

EPICA_residual = ...
    deltaD_base - EPICA_long_term;

% Estimate lag-1 autocorrelation.
x_previous = EPICA_residual(1:end-1);
x_next = EPICA_residual(2:end);

valid_pairs = ...
    isfinite(x_previous) ...
    & isfinite(x_next);

phi_proxy = corr( ...
    x_previous(valid_pairs), ...
    x_next(valid_pairs));

% Avoid an exactly non-stationary AR(1) process.
phi_proxy = max(min(phi_proxy, 0.999), -0.999);

% Target standard deviation for every synthetic realisation.
sigma_proxy = std( ...
    EPICA_residual, ...
    0, ...
    "omitnan");

% Longer burn-in for highly persistent AR(1) processes.
adaptive_burn_in = ceil( ...
    20 / max(1 - abs(phi_proxy), 1e-4));

burn_in = max( ...
    opts.burn_in_steps, ...
    adaptive_burn_in);

fprintf("\nEPICA-derived synthetic parameters:\n");
fprintf("AR(1) phi: %.6f\n", phi_proxy);
fprintf("Target synthetic SD: %.6f\n", sigma_proxy);
fprintf("Burn-in: %d time steps\n", burn_in);
fprintf("Synthetic base grid: %.0f years\n", ...
    1000 * opts.base_dt_kyr);
fprintf("Number of realisations: %d\n", ...
    opts.n_realizations);


% 7. CREATE THE TARGET ANALYSIS GRIDS


n_grid = numel(opts.test_dt_kyr);

GRID = cell(n_grid, 1);

for i_grid = 1:n_grid

    dt = opts.test_dt_kyr(i_grid);

    target_start = ...
        ceil(age_base(1) / dt) * dt;

    target_end = ...
        floor(age_base(end) / dt) * dt;

    GRID{i_grid}.dt_kyr = dt;

    GRID{i_grid}.grid_years = ...
        round(1000 * dt);

    GRID{i_grid}.age = ...
        (target_start:dt:target_end)';

    fprintf( ...
        "%d-year grid: %d points, %.2f--%.2f kyr BP\n", ...
        GRID{i_grid}.grid_years, ...
        numel(GRID{i_grid}.age), ...
        GRID{i_grid}.age(1), ...
        GRID{i_grid}.age(end));

end


% 8. PREALLOCATE ENSEMBLE OUTPUT ARRAYS


n_output = numel(age_output);
n_real = opts.n_realizations;

THIR_Z_CONTROL = cell(n_grid, 1);
THIR_Z_EPICA = cell(n_grid, 1);

HILBERT_Z_CONTROL = cell(n_grid, 1);
HILBERT_Z_EPICA = cell(n_grid, 1);

THIR_PERCENT_BIAS = cell(n_grid, 1);
HILBERT_PERCENT_BIAS = cell(n_grid, 1);

for i_grid = 1:n_grid

    THIR_Z_CONTROL{i_grid} = ...
        nan(n_output, n_real, "single");

    THIR_Z_EPICA{i_grid} = ...
        nan(n_output, n_real, "single");

    HILBERT_Z_CONTROL{i_grid} = ...
        nan(n_output, n_real, "single");

    HILBERT_Z_EPICA{i_grid} = ...
        nan(n_output, n_real, "single");

    THIR_PERCENT_BIAS{i_grid} = ...
        nan(n_output, n_real, "single");

    HILBERT_PERCENT_BIAS{i_grid} = ...
        nan(n_output, n_real, "single");

end


% 9. PAIRED MONTE CARLO EXPERIMENT


rng(opts.random_seed, "twister");

fprintf("\n============================================================\n");
fprintf("RUNNING MONTE CARLO EXPERIMENT\n");
fprintf("============================================================\n");

for first_realisation = 1:opts.chunk_size:opts.n_realizations

    last_realisation = min( ...
        first_realisation + opts.chunk_size - 1, ...
        opts.n_realizations);

    column_indices = ...
        first_realisation:last_realisation;

    n_chunk = numel(column_indices);

    fprintf( ...
        "Realisations %d--%d of %d\n", ...
        first_realisation, ...
        last_realisation, ...
        opts.n_realizations);

    
    % 9.1 Generate AR(1) records on the original 100-year grid
 

    % Unit Gaussian innovations.
    innovations = randn( ...
        numel(age_base) + burn_in, ...
        n_chunk);

    % AR(1):
    %
    % X(t) = phi * X(t-1) + eta(t)
    synthetic_full = filter( ...
        1, ...
        [1, -phi_proxy], ...
        innovations, ...
        [], ...
        1);

    % Remove burn-in.
    synthetic_100yr = ...
        synthetic_full(burn_in + 1:end, :);

    % Standardise every realisation separately and scale it to the
    % EPICA-derived residual standard deviation.
    synthetic_100yr = standardise_to_sigma( ...
        synthetic_100yr, ...
        sigma_proxy);

    
    % 9.2 Sample each 100-year record at the original EPICA ages
    

    synthetic_at_EPICA_ages = interp1( ...
        age_base, ...
        synthetic_100yr, ...
        age_obs, ...
        opts.interp_method);

    
    % 9.3 Process each target analysis grid
    

    for i_grid = 1:n_grid

        dt = GRID{i_grid}.dt_kyr;
        age_target = GRID{i_grid}.age;

        % Uniform control:
        %
        % 100-year synthetic record
        % -> target grid.
        synthetic_control = interp1( ...
            age_base, ...
            synthetic_100yr, ...
            age_target, ...
            opts.interp_method);

        % EPICA-resolution record:
        %
        % 100-year synthetic record
        % -> original EPICA ages
        % -> target grid.
        synthetic_EPICA = interp1( ...
            age_obs, ...
            synthetic_at_EPICA_ages, ...
            age_target, ...
            opts.interp_method);

       
        % 9.4 Thirumalai-style metric
     

        thir_control_raw = thirumalai_metric_raw( ...
            synthetic_control, ...
            dt, ...
            opts);

        thir_EPICA_raw = thirumalai_metric_raw( ...
            synthetic_EPICA, ...
            dt, ...
            opts);

        % Joint standardisation ensures that the control and degraded
        % curves use the same z-score scale within each realisation.
        [thir_control_z, thir_EPICA_z] = ...
            joint_zscore_pair( ...
            thir_control_raw, ...
            thir_EPICA_raw);

        % Smooth the z-score curves.
        thir_control_z_smooth = gaussian_smooth_matrix( ...
            thir_control_z, ...
            dt, ...
            opts.trend_window_kyr);

        thir_EPICA_z_smooth = gaussian_smooth_matrix( ...
            thir_EPICA_z, ...
            dt, ...
            opts.trend_window_kyr);

        % Smooth the raw, positive metrics before percentage calculation.
        thir_control_raw_smooth = gaussian_smooth_matrix( ...
            thir_control_raw, ...
            dt, ...
            opts.trend_window_kyr);

        thir_EPICA_raw_smooth = gaussian_smooth_matrix( ...
            thir_EPICA_raw, ...
            dt, ...
            opts.trend_window_kyr);

        % Calculate percentage bias separately for every paired
        % realisation.
        thir_percent_bias = calculate_percentage_bias( ...
            thir_control_raw_smooth, ...
            thir_EPICA_raw_smooth);

        
        % 9.5 Thesis-style 2--10 kyr Hilbert-amplitude metric
      

        hilbert_control_raw = hilbert_metric_raw( ...
            synthetic_control, ...
            dt, ...
            opts);

        hilbert_EPICA_raw = hilbert_metric_raw( ...
            synthetic_EPICA, ...
            dt, ...
            opts);

        [hilbert_control_z, hilbert_EPICA_z] = ...
            joint_zscore_pair( ...
            hilbert_control_raw, ...
            hilbert_EPICA_raw);

        hilbert_control_z_smooth = gaussian_smooth_matrix( ...
            hilbert_control_z, ...
            dt, ...
            opts.trend_window_kyr);

        hilbert_EPICA_z_smooth = gaussian_smooth_matrix( ...
            hilbert_EPICA_z, ...
            dt, ...
            opts.trend_window_kyr);

        hilbert_control_raw_smooth = gaussian_smooth_matrix( ...
            hilbert_control_raw, ...
            dt, ...
            opts.trend_window_kyr);

        hilbert_EPICA_raw_smooth = gaussian_smooth_matrix( ...
            hilbert_EPICA_raw, ...
            dt, ...
            opts.trend_window_kyr);

        hilbert_percent_bias = calculate_percentage_bias( ...
            hilbert_control_raw_smooth, ...
            hilbert_EPICA_raw_smooth);

        
        % 9.6 Interpolate finished smoothed curves to the common output grid
       

        THIR_Z_CONTROL{i_grid}(:, column_indices) = single( ...
            interp1( ...
            age_target, ...
            thir_control_z_smooth, ...
            age_output, ...
            "linear"));

        THIR_Z_EPICA{i_grid}(:, column_indices) = single( ...
            interp1( ...
            age_target, ...
            thir_EPICA_z_smooth, ...
            age_output, ...
            "linear"));

        HILBERT_Z_CONTROL{i_grid}(:, column_indices) = single( ...
            interp1( ...
            age_target, ...
            hilbert_control_z_smooth, ...
            age_output, ...
            "linear"));

        HILBERT_Z_EPICA{i_grid}(:, column_indices) = single( ...
            interp1( ...
            age_target, ...
            hilbert_EPICA_z_smooth, ...
            age_output, ...
            "linear"));

        THIR_PERCENT_BIAS{i_grid}(:, column_indices) = single( ...
            interp1( ...
            age_target, ...
            thir_percent_bias, ...
            age_output, ...
            "linear"));

        HILBERT_PERCENT_BIAS{i_grid}(:, column_indices) = single( ...
            interp1( ...
            age_target, ...
            hilbert_percent_bias, ...
            age_output, ...
            "linear"));

    end

end

fprintf("\nMonte Carlo experiment completed.\n");


