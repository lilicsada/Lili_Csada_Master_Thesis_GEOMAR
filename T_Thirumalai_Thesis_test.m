function [age, proxy] = read_epica_record( ...
    filename, age_min_kyr, age_max_kyr)

    if ~isfile(filename)

        error("EPICA input file not found: %s", filename);

    end

    raw = readmatrix(filename);

    if size(raw, 2) < 2

        error( ...
            "The EPICA file must contain age and proxy values " + ...
            "in its first two columns.");

    end

    age = raw(:, 1);
    proxy = raw(:, 2);

    valid = ...
        isfinite(age) ...
        & isfinite(proxy);

    age = age(valid);
    proxy = proxy(valid);

    % Convert years to kyr when necessary.
    if max(age, [], "omitnan") > 5000

        age = age / 1000;

    end

    [age, order] = sort(age, "ascend");
    proxy = proxy(order);

    [age, unique_indices] = unique(age, "stable");
    proxy = proxy(unique_indices);

    keep = ...
        age >= age_min_kyr ...
        & age <= age_max_kyr;

    age = age(keep);
    proxy = proxy(keep);

    if numel(age) < 100

        error("Too few valid EPICA observations remain.");

    end

end

function metric = thirumalai_metric_raw( ...
    signal, dt_kyr, opts)

    signal = ensure_column_matrix(signal);

    sampling_frequency = 1 / dt_kyr;
    nyquist_frequency = sampling_frequency / 2;

    highpass_frequency = ...
        1 / opts.thirumalai_cutoff_kyr;

    if highpass_frequency >= nyquist_frequency

        error( ...
            "The <10-kyr high-pass cutoff exceeds Nyquist.");

    end

    [b, a] = butter( ...
        opts.filter_order, ...
        highpass_frequency / nyquist_frequency, ...
        "high");

    npad = calculate_padding_points( ...
        dt_kyr, ...
        opts.pad_kyr, ...
        a, ...
        b);

    padded_signal = mirror_pad_matrix( ...
        signal, ...
        npad);

    filtered_padded = filtfilt( ...
        b, ...
        a, ...
        padded_signal);

    % Number of samples corresponding as closely as possible to a
    % centred 2-kyr rolling window.
    rolling_window_points = max( ...
        3, ...
        round(opts.rolling_window_kyr / dt_kyr) + 1);

    effective_span_kyr = ...
        (rolling_window_points - 1) * dt_kyr;

    persistent printed_grids

    grid_key = ...
        sprintf("g%d", round(1000 * dt_kyr));

    if isempty(printed_grids) ...
            || ~isfield(printed_grids, grid_key)

        fprintf( ...
            "%d-year grid: Thirumalai window = %d points; ", ...
            round(1000 * dt_kyr), ...
            rolling_window_points);

        fprintf( ...
            "effective span = %.2f kyr\n", ...
            effective_span_kyr);

        if isempty(printed_grids)

            printed_grids = struct();

        end

        printed_grids.(grid_key) = true;

    end

    metric_padded = movstd( ...
        filtered_padded, ...
        rolling_window_points, ...
        0, ...
        1, ...
        "omitnan", ...
        "Endpoints", ...
        "shrink");

    n = size(signal, 1);

    metric = metric_padded( ...
        npad + 1:npad + n, :);

end

function amplitude = hilbert_metric_raw( ...
    signal, dt_kyr, opts)

    signal = ensure_column_matrix(signal);

    sampling_frequency = 1 / dt_kyr;
    nyquist_frequency = sampling_frequency / 2;

    frequency_band = [ ...
        1 / opts.hilbert_upper_period_kyr, ...
        1 / opts.hilbert_lower_period_kyr];

    normalised_band = ...
        frequency_band / nyquist_frequency;

    if normalised_band(1) <= 0 ...
            || normalised_band(2) >= 1

        error( ...
            "The 2--10 kyr band cannot be represented for dt = %.3f kyr.", ...
            dt_kyr);

    end

    [b, a] = butter( ...
        opts.filter_order, ...
        normalised_band, ...
        "bandpass");

    npad = calculate_padding_points( ...
        dt_kyr, ...
        opts.pad_kyr, ...
        a, ...
        b);

    padded_signal = mirror_pad_matrix( ...
        signal, ...
        npad);

    filtered_padded = filtfilt( ...
        b, ...
        a, ...
        padded_signal);

    amplitude_padded = abs( ...
        hilbert(filtered_padded));

    n = size(signal, 1);

    amplitude = amplitude_padded( ...
        npad + 1:npad + n, :);

end

function npad = calculate_padding_points( ...
    dt_kyr, pad_kyr, a, b)

    requested_padding = ...
        round(pad_kyr / dt_kyr);

    minimum_filter_padding = ...
        3 * max(length(a), length(b));

    npad = max( ...
        requested_padding, ...
        minimum_filter_padding);

end

function padded_signal = mirror_pad_matrix( ...
    signal, npad)

    signal = ensure_column_matrix(signal);

    n = size(signal, 1);

    if npad >= n

        error( ...
            "Mirror padding must be shorter than the input series.");

    end

    left_padding = ...
        signal(npad + 1:-1:2, :);

    right_padding = ...
        signal(n - 1:-1:n - npad, :);

    padded_signal = [ ...
        left_padding; ...
        signal; ...
        right_padding];

end

function [control_z, EPICA_z] = joint_zscore_pair( ...
    control_metric, EPICA_metric)

    control_metric = ...
        ensure_column_matrix(control_metric);

    EPICA_metric = ...
        ensure_column_matrix(EPICA_metric);

    combined_metric = [ ...
        control_metric; ...
        EPICA_metric];

    common_mean = mean( ...
        combined_metric, ...
        1, ...
        "omitnan");

    common_sigma = std( ...
        combined_metric, ...
        0, ...
        1, ...
        "omitnan");

    common_sigma( ...
        ~isfinite(common_sigma) ...
        | common_sigma <= eps) = 1;

    control_z = ...
        (control_metric - common_mean) ...
        ./ common_sigma;

    EPICA_z = ...
        (EPICA_metric - common_mean) ...
        ./ common_sigma;

end

function bias_percent = calculate_percentage_bias( ...
    control_metric, EPICA_metric)

    control_metric = ...
        ensure_column_matrix(control_metric);

    EPICA_metric = ...
        ensure_column_matrix(EPICA_metric);

    denominator = control_metric;

    % Protect against division by a very small value.
    minimum_denominator = ...
        1e-8 .* median( ...
        abs(control_metric), ...
        1, ...
        "omitnan");

    minimum_denominator( ...
        ~isfinite(minimum_denominator) ...
        | minimum_denominator <= eps) = eps;

    for i_column = 1:size(denominator, 2)

        too_small = ...
            abs(denominator(:, i_column)) ...
            < minimum_denominator(i_column);

        denominator(too_small, i_column) = ...
            minimum_denominator(i_column);

    end

    bias_percent = ...
        100 .* ...
        (EPICA_metric - control_metric) ...
        ./ denominator;

end

function smoothed = gaussian_smooth_matrix( ...
    signal, dt_kyr, window_kyr)

    signal = ensure_column_matrix(signal);

    window_points = max( ...
        3, ...
        round(window_kyr / dt_kyr));

    if mod(window_points, 2) == 0

        window_points = ...
            window_points + 1;

    end

    half_window = floor( ...
        window_points / 2);

    kernel_axis = ...
        (-half_window:half_window)';

    % This represents a Gaussian kernel contained within a total
    % window of approximately window_kyr.
    sigma_points = max( ...
        window_points / 6, ...
        1);

    kernel = exp( ...
        -0.5 .* ...
        (kernel_axis ./ sigma_points).^2);

    kernel = ...
        kernel ./ sum(kernel);

    valid = isfinite(signal);

    signal_zero = signal;
    signal_zero(~valid) = 0;

    numerator = conv2( ...
        signal_zero, ...
        kernel, ...
        "same");

    denominator = conv2( ...
        double(valid), ...
        kernel, ...
        "same");

    smoothed = ...
        numerator ./ max(denominator, eps);

    smoothed(denominator <= eps) = NaN;

end

function output = standardise_to_sigma( ...
    signal, target_sigma)

    signal = ensure_column_matrix(signal);

    % Centre each synthetic realisation separately.
    signal = signal - mean( ...
        signal, ...
        1, ...
        "omitnan");

    % Calculate the sample SD of each realisation.
    current_sigma = std( ...
        signal, ...
        0, ...
        1, ...
        "omitnan");

    current_sigma( ...
        ~isfinite(current_sigma) ...
        | current_sigma <= eps) = 1;

    % Give every realisation exactly the same target SD.
    output = ...
        signal ./ current_sigma ...
        .* target_sigma;

end

