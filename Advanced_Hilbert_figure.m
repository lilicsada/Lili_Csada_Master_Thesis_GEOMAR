%% ============================================================
% FUNCTION:
% SET Y LIMITS
%% ============================================================

function set_nice_ylim_local( ...
    ax, ...
    y)


    y = ...
        y(isfinite(y));


    if isempty(y)


        ylim( ...
            ax, ...
            [-1 1]);


        return


    end


    minimum_y = ...
        min(y);


    maximum_y = ...
        max(y);


    y_range = ...
        maximum_y - ...
        minimum_y;


    if y_range == 0


        y_range = ...
            max( ...
            abs(maximum_y), ...
            1);


        minimum_y = ...
            minimum_y - ...
            0.5 * y_range;


        maximum_y = ...
            maximum_y + ...
            0.5 * y_range;


    end


    padding = ...
        0.08 * y_range;


    ylim( ...
        ax, ...
        [ ...
        minimum_y - padding ...
        maximum_y + padding ...
        ]);


end



%% ============================================================
% FUNCTION:
% FORMAT Y AXIS
%% ============================================================

function format_y_axis_local( ...
    ax, ...
    number_of_ticks)


    current_ylim = ...
        ylim(ax);


    y_ticks = ...
        linspace( ...
        current_ylim(1), ...
        current_ylim(2), ...
        number_of_ticks);


    ax.YTick = ...
        y_ticks;


    tick_labels = ...
        strings( ...
        size(y_ticks));


    for k = 1:numel(y_ticks)


        if ...
                abs( ...
                y_ticks(k) - ...
                round(y_ticks(k))) ...
                < 1e-8


            tick_labels(k) = ...
                sprintf( ...
                "%.0f", ...
                y_ticks(k));


        else


            tick_labels(k) = ...
                sprintf( ...
                "%.1f", ...
                y_ticks(k));


        end


    end


    tick_labels(1) = ...
        "";


    tick_labels(end) = ...
        "";


    ax.YTickLabel = ...
        tick_labels;


end



