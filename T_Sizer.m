% LOCAL FUNCTION:
% FIND ABRAM SIZER FOLDER


function folder = ...
    find_abram_sizer_folder( ...
    root_dir)


    candidates = {

        fullfile( ...
        root_dir, ...
        'sizer')

        fullfile( ...
        root_dir, ...
        'AbrametalPAGES2k2016_Supp3_code', ...
        'sizer')

        };


    for i = 1:numel(candidates)


        if isfile( ...
                fullfile( ...
                candidates{i}, ...
                'sz2SM_edit.m'))


            folder = ...
                candidates{i};


            return;


        end


    end



    hit = ...
        dir( ...
        fullfile( ...
        root_dir, ...
        '**', ...
        'sz2SM_edit.m'));



    if ~isempty(hit)


        folder = ...
            hit(1).folder;


        return;


    end



    error( ...
        [ ...
        'Could not find sz2SM_edit.m. Extract the complete ' ...
        'AbrametalPAGES2k2016_Supp3_code folder beside this script.' ...
        ]);


end


% LOCAL FUNCTION:
% FIND RECORD INDEX FROM LABEL


function idx = ...
    find_record_index( ...
    labels, ...
    pattern)


    matches = ...
        find( ...
        contains( ...
        labels, ...
        lower( ...
        string(pattern))));


    if isempty(matches)


        error( ...
            'Could not find a record label containing "%s".', ...
            char(pattern));


    end



    if numel(matches) > 1


        warning( ...
            'Multiple labels contain "%s"; using the first.', ...
            char(pattern));


    end



    idx = ...
        matches(1);


end




% LOCAL FUNCTION:
