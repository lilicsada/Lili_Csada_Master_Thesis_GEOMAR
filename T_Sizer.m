function runs = ...
    get_runs( ...
    age, ...
    mask, ...
    min_run, ...
    young_limit, ...
    old_limit)


    age = ...
        age(:);


    mask = ...
        logical( ...
        mask(:)');


    runs = ...
        struct( ...
        'young_edge_age', ...
        {}, ...
        'old_edge_age', ...
        {}, ...
        'duration', ...
        {});


    if ...
            isempty(mask) || ...
            ~any(mask)


        return;


    end



    difference = ...
        diff( ...
        [ ...
        0 ...
        mask ...
        0 ...
        ]);


    start_indices = ...
        find( ...
        difference == 1);


    end_indices = ...
        find( ...
        difference == -1) - ...
        1;



    for k = 1:numel(start_indices)


        young = ...
            age( ...
            start_indices(k));


        old = ...
            age( ...
            end_indices(k));


        duration = ...
            old - ...
            young;



        if ...
                old <= ...
                young_limit || ...
                old >= ...
                old_limit


            continue;


        end



        if duration >= ...
                min_run


            runs( ...
                end + 1).young_edge_age = ...
                young;


            runs(end).old_edge_age = ...
                old;


            runs(end).duration = ...
                duration;


        end


    end


end



function clusters = ...
    cluster_onsets( ...
    ages, ...
    bws, ...
    signs, ...
    gap, ...
    min_bws, ...
    unc_mode)


    clusters = ...
        struct( ...
        'median_age', ...
        {}, ...
        'p10_age', ...
        {}, ...
        'p90_age', ...
        {}, ...
        'q25_age', ...
        {}, ...
        'q75_age', ...
        {}, ...
        'unc_low_age', ...
        {}, ...
        'unc_high_age', ...
        {}, ...
        'sign', ...
        {}, ...
        'n_points', ...
        {}, ...
        'n_bandwidths', ...
        {}, ...
        'ages', ...
        {}, ...
        'bandwidths', ...
        {});


    if isempty(ages)


        return;


    end



    sign_values = ...
        unique( ...
        signs( ...
        isfinite( ...
        signs)));



    for ss = 1:numel(sign_values)


        this_sign = ...
            sign_values(ss);


        use = ...
            signs == ...
            this_sign & ...
            isfinite(ages) & ...
            isfinite(bws);


        a = ...
            ages(use);


        b = ...
            bws(use);


        if isempty(a)


            continue;


        end



        [a, idx] = ...
            sort(a);


        b = ...
            b(idx);


        current_a = ...
            a(1);


        current_b = ...
            b(1);



        for i = 2:numel(a)


            if ...
                    a(i) - ...
                    a(i - 1) <= ...
                    gap


                current_a( ...
                    end + 1, ...
                    1) = ...
                    a(i);


                current_b( ...
                    end + 1, ...
                    1) = ...
                    b(i);


            else


                clusters = ...
                    add_cluster( ...
                    clusters, ...
                    current_a, ...
                    current_b, ...
                    this_sign, ...
                    min_bws, ...
                    unc_mode);


                current_a = ...
                    a(i);


                current_b = ...
                    b(i);


            end


        end



        clusters = ...
            add_cluster( ...
            clusters, ...
            current_a, ...
            current_b, ...
            this_sign, ...
            min_bws, ...
            unc_mode);


    end



    if ~isempty(clusters)


        [~, idx] = ...
            sort( ...
            [ ...
            clusters.median_age ...
            ], ...
            'descend');


        clusters = ...
            clusters(idx);


    end


end



function clusters = ...
    add_cluster( ...
    clusters, ...
    ages, ...
    bws, ...
    sgn, ...
    min_bws, ...
    unc_mode)


    unique_bws = ...
        unique(bws);


    if numel(unique_bws) < ...
            min_bws


        return;


    end



    p10 = ...
        local_percentile( ...
        ages, ...
        10);


    p90 = ...
        local_percentile( ...
        ages, ...
        90);


    q25 = ...
        local_percentile( ...
        ages, ...
        25);


    q75 = ...
        local_percentile( ...
        ages, ...
        75);



    switch lower( ...
            string( ...
            unc_mode))


        case "p10_p90"


            lo = ...
                p10;


            hi = ...
                p90;



        case "iqr"


            lo = ...
                q25;


            hi = ...
                q75;



        case "range"


            lo = ...
                min( ...
                ages, ...
                [], ...
                'omitnan');


            hi = ...
                max( ...
                ages, ...
                [], ...
                'omitnan');



        otherwise


            error( ...
                'Unknown uncertainty mode: %s', ...
                char( ...
                unc_mode));


    end



    clusters( ...
        end + 1).median_age = ...
        median( ...
        ages, ...
        'omitnan');


    clusters(end).p10_age = ...
        p10;


    clusters(end).p90_age = ...
        p90;


    clusters(end).q25_age = ...
        q25;


    clusters(end).q75_age = ...
        q75;


    clusters(end).unc_low_age = ...
        lo;


    clusters(end).unc_high_age = ...
        hi;


    clusters(end).sign = ...
        sgn;


    clusters(end).n_points = ...
        numel(ages);


    clusters(end).n_bandwidths = ...
        numel(unique_bws);


    clusters(end).ages = ...
        ages;


    clusters(end).bandwidths = ...
        bws;


end



function v = ...
    local_percentile( ...
    x, ...
    p)


    x = ...
        sort( ...
        x( ...
        isfinite(x)));


    if isempty(x)


        v = ...
            NaN;


        return;


    end



    x = ...
        x(:);


    n = ...
        numel(x);


    if n == 1


        v = ...
            x;


        return;


    end



    position = ...
        1 + ...
        ( ...
        p / ...
        100 ...
        ) * ...
        ( ...
        n - ...
        1 ...
        );


    lo = ...
        floor( ...
        position);


    hi = ...
        ceil( ...
        position);



    if lo == hi


        v = ...
            x(lo);


    else


        weight = ...
            position - ...
            lo;


        v = ...
            ( ...
            1 - ...
            weight ...
            ) * ...
            x(lo) + ...
            weight * ...
            x(hi);


    end


end


